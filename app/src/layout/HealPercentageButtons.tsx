"use client";

import { Button, type ButtonProps } from "@/components/ui/button";
import { calcChakraToPools } from "@/libs/hospital";
import { calcCurrent } from "@/libs/regeneration";
import { cn } from "@/libs/shadui";
import type { UserWithRelations } from "@/routers/profile";

/** The shares of a target's health a healer can restore in one heal. */
export const HEAL_PERCENTAGES = [0.25, 0.5, 0.75, 1.0];

/** One button per heal share; each needs the capacity for its share and missing health for it. */
export const HealPercentageButtons = ({
  maxHealth,
  missingHealth,
  maxHeal,
  onHeal,
  disabled = false,
  className,
  buttonProps,
}: {
  /** Health pool of the target */
  maxHealth: number;
  /** Health the target is missing */
  missingHealth: number;
  /** Capacity of the healer, in health points */
  maxHeal: number;
  onHeal: (healPercentage: number) => void;
  /** Disable every share */
  disabled?: boolean;
  className?: string;
  buttonProps?: Pick<ButtonProps, "className" | "role">;
}) => (
  <div className={cn("grid grid-cols-2", className)}>
    {HEAL_PERCENTAGES.map((share, index) => {
      const previousShare = HEAL_PERCENTAGES[index - 1];
      return (
        <Button
          key={share}
          {...buttonProps}
          disabled={
            disabled ||
            maxHealth * share > maxHeal ||
            (previousShare !== undefined && missingHealth <= previousShare * maxHealth)
          }
          onClick={() => onHeal(share * 100)}
        >
          {share * 100}%
        </Button>
      );
    })}
  </div>
);

/** Chakra the healer has now, including what has regenerated past the `userData` snapshot. */
export const currentChakra = (
  userData: NonNullable<UserWithRelations>,
  timeDiff: number,
) =>
  calcCurrent(
    userData.curChakra,
    userData.maxChakra,
    userData.status,
    userData.regeneration,
    userData.regenAt,
    timeDiff,
  ).current;

/** How much the healer can heal right now, with the chakra they have regenerated by now. */
export const currentHealCapacity = (
  userData: NonNullable<UserWithRelations>,
  timeDiff: number,
) => calcChakraToPools(userData, currentChakra(userData, timeDiff));
