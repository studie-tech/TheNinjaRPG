// Helper: find banned word in a username.
// Username allows only [a-zA-Z0-9_]. We split on '_' and compare tokens to the banned set.
export const findBannedWordInUsername = (username: string): string | undefined => {
  const lower = username.toLowerCase();
  const tokens = lower.split("_").filter(Boolean);
  if (tokens.length === 0) tokens.push(lower);
  const offensiveSet = new Set(OFFENSIVE_WORDS.map((w) => w.toLowerCase()));
  return tokens.find((t) => offensiveSet.has(t));
};
