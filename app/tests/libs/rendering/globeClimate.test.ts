import { describe, expect, it } from "bun:test";
import globe from "@/data/hexasphere.json";
import {
  buildGlobeClimate,
  GLOBE_CLIMATE_HEIGHT,
  GLOBE_CLIMATE_RANGES,
  GLOBE_CLIMATE_WIDTH,
} from "@/libs/rendering/globeClimate";
import { createSectorWorkerHandler } from "@/libs/rendering/sectorGeneration";
import type { GlobalMapData } from "@/libs/sector-map/world-types";

const map = globe as unknown as GlobalMapData;
const protectedSectors = map.protectedLandSectors ?? [];

describe("globe climate field", () => {
  it("paints the same biome type the globe assigns each sector", () => {
    const texels = buildGlobeClimate(protectedSectors);
    const mismatches: number[] = [];
    for (const [sector, tile] of map.tiles.entries()) {
      const climate = sampleClimate(texels, tile.c);
      if (biomeOf(climate) !== tile.t) mismatches.push(sector);
    }
    // Quantization moves a sector only when its centre sits on a biome threshold.
    expect(mismatches.length / map.tiles.length).toBeLessThan(0.01);
  });

  it("is generated by the shared worker and handed over without copying", () => {
    const { reply, transfer } = createSectorWorkerHandler()({
      id: 7,
      type: "globe",
      request: { protectedSectors },
    });
    expect("result" in reply && reply.result instanceof Uint8Array).toBe(true);
    const result = "result" in reply ? (reply.result as Uint8Array) : null;
    expect(result?.length).toBe(GLOBE_CLIMATE_WIDTH * GLOBE_CLIMATE_HEIGHT * 4);
    expect(transfer).toEqual([result?.buffer as ArrayBuffer]);
  });
});

/** Bilinear lookup at a sector centre, mirroring the shader's equirectangular mapping. */
const sampleClimate = (
  texels: Uint8Array,
  point: { x: number; y: number; z: number },
) => {
  const length = Math.hypot(point.x, point.y, point.z);
  const u =
    (Math.atan2(point.z, point.x) / (2 * Math.PI) + 0.5) * GLOBE_CLIMATE_WIDTH - 0.5;
  const v = (0.5 - Math.asin(point.y / length) / Math.PI) * GLOBE_CLIMATE_HEIGHT - 0.5;
  const column = Math.floor(u),
    row = Math.floor(v);
  const at = (c: number, r: number, channel: number) =>
    texels[
      (Math.min(GLOBE_CLIMATE_HEIGHT - 1, Math.max(0, r)) * GLOBE_CLIMATE_WIDTH +
        ((c + GLOBE_CLIMATE_WIDTH) % GLOBE_CLIMATE_WIDTH)) *
        4 +
        channel
    ] ?? 0;
  const channel = (index: number, [low, high]: readonly [number, number]) => {
    const fu = u - column,
      fv = v - row;
    const top = at(column, row, index) * (1 - fu) + at(column + 1, row, index) * fu;
    const bottom =
      at(column, row + 1, index) * (1 - fu) + at(column + 1, row + 1, index) * fu;
    return low + ((top * (1 - fv) + bottom * fv) / 255) * (high - low);
  };
  return {
    land: channel(0, GLOBE_CLIMATE_RANGES.land),
    temperature: channel(2, GLOBE_CLIMATE_RANGES.temperature),
    moisture: channel(3, GLOBE_CLIMATE_RANGES.moisture),
  };
};

/** `globalBiomeType`'s thresholds over decoded climate values. */
const biomeOf = (climate: ReturnType<typeof sampleClimate>) => {
  if (climate.land <= 0) return 0;
  if (climate.temperature < -0.14) return 3;
  if (climate.temperature > 0.12 && climate.moisture < -0.08) return 2;
  return 1;
};
