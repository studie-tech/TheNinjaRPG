/** Forbidden variants: same stats as the base legendary, `baseCardId` set. */
export const KESSEN_FORBIDDEN: KessenCard[] = FORBIDDEN.map(([baseName, name]) => {
  const base = KESSEN_DECK_CARDS.find((entry) => entry.name === baseName);
  if (!base) throw new Error(`Unknown Forbidden base ${baseName}`);
  const id = kessenCardId(baseName, "forbidden");
  KESSEN_SEED_DISPLAY[id] = {
    number: null,
    flavor: KESSEN_SEED_DISPLAY[base.id]?.flavor ?? "",
  };
  return { ...base, id, name, variant: "FORBIDDEN", baseCardId: base.id };
});

