interface LeaderInput {
  name: string;
  /** Ability title, stored as the Item description prefix ("Sunflare: ..."). */
  title: string;
  faction: KessenFaction;
  rarity: KessenRarity;
  bonus: number;
  abilities: KessenAbility[];
  collectible?: boolean;
}

const leader = (input: LeaderInput): KessenCard => {
  const id = kessenCardId(input.name, "leader");
  KESSEN_SEED_DISPLAY[id] = {
    number: null,
    flavor: "",
    abilityName: input.title,
  };
  return {
    id,
    name: input.name,
    rarity: input.rarity,
    kind: "LEADER",
    faction: input.faction,
    row: null,
    power: 0,
    provision: 0,
    abilities: input.abilities,
    sets: [],
    leaderBonus: input.bonus,
    variant: "STANDARD",
    baseCardId: null,
    isCollectible: input.collectible ?? true,
  };
};

