/** Display data of a seed card: its collection number, flavor text and leader ability title. */
export interface KessenSeedDisplay {
  number: number | null;
  flavor: string;
  abilityName?: string;
}

export const KESSEN_SEED_DISPLAY: Record<string, KessenSeedDisplay> = {};

interface CardInput {
  n: number;
  name: string;
  /** Item id when the name is not its slug (Item names are unique across the game). */
  id?: string;
  faction: KessenFaction;
  rarity: KessenRarity;
  kind: "UNIT" | "TACTIC";
  row: KessenCard["row"];
  power: number;
  provision: number;
  abilities: KessenAbility[];
  sets: string[];
  flavor: string;
}

const card = (input: CardInput): KessenCard => {
  const id = input.id ?? kessenCardId(input.name);
  KESSEN_SEED_DISPLAY[id] = {
    number: input.n,
    flavor: input.flavor,
  };
  return {
    id,
    name: input.name,
    rarity: input.rarity,
    kind: input.kind,
    faction: input.faction,
    row: input.row,
    power: input.power,
    provision: input.provision,
    abilities: input.abilities,
    sets: input.sets,
    leaderBonus: 0,
    variant: "STANDARD",
    baseCardId: null,
    isCollectible: true,
  };
};

const strike = (
  x: number,
  mode: "single" | "oppositeRow" | "chosenRow" | "allEnemies" = "single",
): KessenAbility => ({ k: "strike", x, mode });

const empower = (
  x: number,
  mode: "single" | "ownRowOthers" | "chosenRow" | "allMine",
): KessenAbility => ({ k: "empower", x, mode });

