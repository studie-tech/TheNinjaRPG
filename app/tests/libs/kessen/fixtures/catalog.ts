/** Seed card by exact name (deck cards and leaders; Forbidden names are distinct). */
export const seedCardByName = (name: string) => {
  const found = [...KESSEN_DECK_CARDS, ...KESSEN_LEADERS].find(
    (entry) => entry.name === name,
  );
  if (!found) throw new Error(`Unknown seed card ${name}`);
  return found;
};
