/** Card id of a frozen card by name. */
export const rulesCardId = (name: string) => {
  const card = KESSEN_RULES_CATALOG.find((entry) => entry.name === name);
  if (!card) throw new Error(`Unknown rules card ${name}`);
  return card.id;
};

